'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const M = require('../src/ui/ghost/case-model');
const R = require('../src/main/ghost/app/report');

function sample() {
  const c = M.newCase('Report <b>case</b>');
  const s = M.addSource(c, { connector: 'dns-doh', connectorVersion: '1.0.0', query: { kind: 'domain', value: 'example.org' }, origin: 'https://doh.example/dns-query?name=x', licence: 'MIT', rawSha256: 'b'.repeat(64) });
  const a = M.addEntity(c, { type: 'domain', value: 'example.org', label: '<script>alert(1)</script>.example', sources: [s], attrs: { note: '"><img src=x onerror=alert(1)>' } }).id;
  const b = M.addEntity(c, { type: 'ip', value: '203.0.113.5', sources: [s] }).id; M.addEdge(c, { from: a, to: b, rel: 'resolves-to', sources: [s] });
  M.addEntity(c, { type: 'place', value: '51.5,-0.1', label: 'Hidden site', manual: true, attrs: { lat: 51.5, lon: -0.1 } });
  return { c, a, b };
}
test('html report: escaped, no script, no external address, attribution footer', () => {
  const { c } = sample(); const html = R.reportHtml(c, { author: 'A <i>Analyst</i>', now: Date.UTC(2026, 0, 2), version: '1.0.0' });
  assert.equal(/<script/i.test(html), false); assert.equal(/<img/i.test(html), false); assert.equal(/onerror=/i.test(html.replace(/&quot;|&gt;|&lt;/g, '')) && /<[^>]*onerror=/i.test(html), false);
  assert.equal(/(src|href)=["']https?:/i.test(html), false, 'no external references');
  assert.ok(html.includes('Made with Mayfair Ghost. Copyright The Mayfair Organization.')); assert.ok(html.includes('&lt;script&gt;'));
  assert.ok(html.includes('Method and limits')); assert.match(html, /[0-9a-f]{64}/); assert.equal(/\bAI\b|artificial intelligence|generated by (an )?(AI|model)/.test(html), false);
});
test('hidden entities are left out with their links', () => {
  const { c, a } = sample(); const html = R.reportHtml(c, { hide: [a] }); assert.equal(html.includes('&lt;script&gt;'), false); assert.ok(html.includes('203.0.113.5'));
  const d = R.reportData(c, { hide: [a] }); assert.equal(d.edges.length, 0);
});
test('json report carries a hash and changes when the case changes', () => {
  const { c } = sample(); const j1 = JSON.parse(R.reportJson(c, { now: 1 })); assert.match(JSON.stringify(j1), /[0-9a-f]{64}/);
  M.addEntity(c, { type: 'domain', value: 'new.example', manual: true }); const j2 = JSON.parse(R.reportJson(c, { now: 1 })); assert.notEqual(JSON.stringify(j1), JSON.stringify(j2));
});
test('the report text has a fixed footer and the copyright is the organization only', () => { assert.equal(R.FOOTER, 'Made with Mayfair Ghost. Copyright The Mayfair Organization.'); });
